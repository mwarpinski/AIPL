#!/usr/bin/env python3
"""Benchmarks (benchmarks/<name>/): builds each program four ways and times
them on the same input, after checking every version prints the same
output as the C reference.

    python3 tools/bench.py              # every benchmark
    python3 tools/bench.py spigot       # one
    python3 tools/bench.py --quick      # each benchmark's test size only
    python3 tools/bench.py --runs 5 --no-python   # best of 5, without Python

Ways: AIPL native (`aipl compile --exe`), AIPL wasm under the launcher
(`--target wasm`, wasmtime/Cranelift), each also built without the
optimizer (`--no-opt`, docs/design/OPT_PLAN.md), C (`gcc -O2`), Python 3.
`--no-unopt` leaves the `--no-opt` builds out. Each time is
the best of RUNS runs, wall clock, process start included. Needs gcc, and a compiler: the self-hosted one
(`sh bootstrap/build.sh`, then `AIPL=target/bootstrap/aipl python3 tools/bench.py`, or `--aipl PATH`), which builds the
native versions and needs no Rust; or the Rust one (`cargo build --release`, the default when it exists), which builds
the wasm versions as well. Prints a Markdown table.
"""
import os, subprocess, sys, time, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BENCH = os.path.join(ROOT, "benchmarks")
OUT = os.path.join(ROOT, "target", "bench")
RUST = os.path.join(ROOT, "target", "release", "aipl")
SELF = os.path.join(ROOT, "target", "bootstrap", "aipl")
RUNS = 3
AIPL = RUST
# (set by main) whether the compiler can also build the wasm versions: they bundle the launcher, aipl-run, from Rust
WASM = True

def sizes(name):
    """(test args, benchmark args) from the benchmark's files."""
    d = os.path.join(BENCH, name)
    test = open(os.path.join(d, "test_args")).read().split()
    bench = open(os.path.join(d, "bench_args")).read().split()
    return test, bench

def build(name):
    src = os.path.join(BENCH, name)
    os.makedirs(OUT, exist_ok=True)
    exe = {}
    for target in ["native", "wasm"] if WASM else ["native"]:
        for opt in ["", "--no-opt"]:
            key = target + opt
            exe[key] = os.path.join(OUT, f"{name}_{target}{opt.replace('-', '_')}")
            subprocess.run([AIPL, "compile", "--exe"] + (["--target=wasm"] if target == "wasm" else []) + ([opt] if opt else []) + [os.path.join(src, f"{name}.aipl"), "-o", exe[key]],
                           check=True, capture_output=True, env=dict(os.environ, AIPL_RUNNER=os.path.join(ROOT, "target", "release", "aipl-run"),
                                    **({} if "AIPL_STD" in os.environ else {"AIPL_STD": os.path.join(ROOT, "aipl_src", "std") + "/"})))
    exe["c"] = os.path.join(OUT, f"{name}_c")
    c = os.path.join(src, f"{name}.c")
    libs = ["-lm"] + (["-lgmp"] if "#include <gmp.h>" in open(c).read() else [])
    built = subprocess.run(["gcc", "-O2", "-o", exe["c"], c] + libs, capture_output=True)
    ways = {
        "AIPL native": [exe["native"]],
        "AIPL native --no-opt": [exe["native--no-opt"]],
        "AIPL wasm (wasmtime)": [exe.get("wasm")],
        "AIPL wasm --no-opt": [exe.get("wasm--no-opt")],
        "C (gcc -O2)": [exe["c"]],
        "Python 3": [sys.executable, os.path.join(src, f"{name}.py")],
    }
    if not WASM:
        del ways["AIPL wasm (wasmtime)"], ways["AIPL wasm --no-opt"]
    if built.returncode != 0:
        # pidigits' C needs GMP (libgmp-dev): its row then has no C time,
        # and no ratios
        print(f"{name}: no C version: {built.stderr.decode().strip().splitlines()[0]}", file=sys.stderr)
        del ways["C (gcc -O2)"]
    return ways

def run(cmd, args, stdin):
    t = time.perf_counter()
    p = subprocess.run(cmd + args, input=stdin, capture_output=True, cwd=os.path.join(BENCH))
    return time.perf_counter() - t, p

def stdin_for(name, quick):
    """The benchmark's input: its `stdin` file at the test size; at the
    benchmark size, generated by its `stdin_cmd` (a Python script and its
    arguments, run from the benchmark's directory) if it has one."""
    d = os.path.join(BENCH, name)
    cmd = os.path.join(d, "stdin_cmd")
    if not quick and os.path.exists(cmd):
        script, *args = open(cmd).read().split()
        return subprocess.run([sys.executable, os.path.join(d, script)] + args, check=True, capture_output=True).stdout
    p = os.path.join(d, "stdin")
    return open(p, "rb").read() if os.path.exists(p) else b""

def main():
    global RUNS, AIPL, WASM
    if "--aipl" in sys.argv:
        i = sys.argv.index("--aipl")
        os.environ["AIPL"] = os.path.abspath(sys.argv.pop(i + 1))
        sys.argv.pop(i)
    # the compiler: --aipl, else $AIPL, else the Rust one if it is built, else the self-hosted one
    AIPL = os.path.abspath(os.environ.get("AIPL") or (RUST if os.path.exists(RUST) else SELF))
    if not os.path.exists(AIPL):
        sys.exit(f"no compiler at {AIPL}: run `sh bootstrap/build.sh` (or `cargo build --release`), or pass --aipl PATH")
    WASM = os.path.exists(os.path.join(os.path.dirname(AIPL), "aipl-run"))
    quick = "--quick" in sys.argv
    if "--runs" in sys.argv:
        i = sys.argv.index("--runs")
        RUNS = int(sys.argv.pop(i + 1))
        sys.argv.pop(i)
    names = [a for a in sys.argv[1:] if not a.startswith("--")] or sorted(
        n for n in os.listdir(BENCH) if os.path.isdir(os.path.join(BENCH, n)))
    rows = []
    for name in names:
        test, bench = sizes(name)
        args = test if quick else bench
        cmds = build(name)
        if "--no-python" in sys.argv:
            del cmds["Python 3"]
        if "--no-unopt" in sys.argv:
            for w in ("AIPL native --no-opt", "AIPL wasm --no-opt"):
                cmds.pop(w, None)
        stdin = stdin_for(name, quick)
        reference = None
        times = {}
        for way, cmd in cmds.items():
            best = None
            for _ in range(RUNS):
                t, p = run(cmd, args, stdin)
                if p.returncode != 0:
                    sys.exit(f"{name} / {way}: exit {p.returncode}: {p.stderr.decode()[:300]}")
                if reference is None:
                    reference = p.stdout
                elif p.stdout != reference:
                    sys.exit(f"{name} / {way}: output differs from the first version's")
                best = t if best is None else min(best, t)
            times[way] = best
        label = " ".join(args)
        cmd = os.path.join(BENCH, name, "stdin_cmd")
        if not quick and os.path.exists(cmd):
            label = (label + " < " if label else "stdin: ") + open(cmd).read().strip()
        rows.append((name, label, times))
    ways = max((list(r[2].keys()) for r in rows), key=len)
    print("| Benchmark | Input | " + " | ".join(ways) + " |")
    print("|---|---|" + "---|" * len(ways))
    for name, args, times in rows:
        c = times.get("C (gcc -O2)")
        cells = [("n/a" if w not in times else f"{times[w]:.3f} s" + (f" ({times[w] / c:.1f}x)" if c else "")) for w in ways]
        print(f"| {name} | {args} | " + " | ".join(cells) + " |")

if __name__ == "__main__":
    main()
