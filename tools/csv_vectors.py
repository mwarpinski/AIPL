"""std/csv's test vectors (tests/aipl/csv/): random short texts over an
alphabet heavy in quotes, delimiters, and line breaks (\\n, \\r\\n, a lone
\\r), read as Python's csv.reader reads them (newline='', the default
dialect); and random rows written as Python's csv.writer writes them.

    python3 tools/csv_vectors.py tests/aipl/csv [seed]

tests/test_csv.rs runs the program in every backend against the answers.
"""
import csv, io, random, sys
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 1)
out = sys.argv[1]
alpha = ["a", "b", "xy", ",", '"', "\n", "\r", "\r\n", '""', " ", ";"]

def lit(s):  # an AIPL string literal for s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r") + '"'

def esc(s):  # a field on one line
    return s.replace("\\", "\\\\").replace("\n", "\\n").replace("\r", "\\r")

def rows_line(rows):
    return "".join("[" + "|".join(esc(f) for f in r) + "]" for r in rows)

lines, want = [], []
for _ in range(400):
    t = "".join(random.choice(alpha) for _ in range(random.randint(0, 14)))
    delim = random.choice([",", ",", ";"])
    rows = list(csv.reader(io.StringIO(t, newline=""), delimiter=delim))
    lines.append(f"    (call read_case {lit(t)} {ord(delim)})")
    want.append(rows_line(rows))
for _ in range(200):
    row = ["".join(random.choice(alpha) for _ in range(random.randint(0, 4))) for _ in range(random.randint(0, 3))]
    s = io.StringIO()
    csv.writer(s).writerow(row)
    padded = row + [""] * (3 - len(row))
    lines.append(f"    (call write_case {len(row)} " + " ".join(lit(f) for f in padded) + ")")
    want.append(esc(s.getvalue()))

src = ''';; Generated by tools/csv_vectors.py; do not edit.
(module vectors
  (import csv)
  (import str)
  (import buf)
  (import alloc)
  (import stream)

  ;; a field on one line, as the generator escapes it
  (fn esc [o:(ptr buf.Buf) s:(ptr str.Bytes)] -> void
    (for i 0 (get s str.Bytes.len)
      (let c:i32 (call str.byte_at s i))
      (cond ((eq c 92) (call buf.push_str o "\\\\\\\\")) ((eq c 10) (call buf.push_str o "\\\\n")) ((eq c 13) (call buf.push_str o "\\\\r"))
            (else (call buf.push_byte o c)))))

  (fn read_case [t:str delim:i32] -> void
    (let a:alloc.Allocator (call alloc.default))
    (let cr:(ptr csv.Reader) (call csv.reader_with a (call stream.of_str a t) delim))
    (let o:(ptr buf.Buf) (call buf.make a 64))
    (while (call csv.next_row cr)
      (call buf.push_byte o 91)
      (for k 0 (call csv.count cr)
        (when (gt k 0) (call buf.push_byte o 124))
        (call esc o (call csv.field cr k)))
      (call buf.push_byte o 93))
    (call csv.close cr)
    (call buf.push_byte o 10)
    (call buf.print o)
    (call buf.free o))

  ;; a row of the first n of f0, f1, f2
  (fn write_case [n:i32 f0:str f1:str f2:str] -> void
    (let a:alloc.Allocator (call alloc.default))
    (let b:(ptr buf.Buf) (call buf.make a 64))
    (let w:(ptr stream.Writer) (call stream.to_buf a b))
    (let cw:(ptr csv.Writer) (call csv.writer a w))
    (when (gt n 0) (call csv.field_str cw f0))
    (when (gt n 1) (call csv.field_str cw f1))
    (when (gt n 2) (call csv.field_str cw f2))
    (call csv.end_row cw)
    (let _ok:bool (call stream.close_writer w))
    (let o:(ptr buf.Buf) (call buf.make a 64))
    (call esc o (call buf.bytes b))
    (call buf.push_byte o 10)
    (call buf.print o)
    (call buf.free o)
    (call buf.free b))

  (fn main [] -> i32
''' + "\n".join(lines) + '''
    0))
'''
open(f"{out}/vectors.aipl", "w").write(src)
open(f"{out}/vectors.expected", "w").write("".join(w + "\n" for w in want))
print(f"{len(want)} cases")
