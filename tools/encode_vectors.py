"""std/encode's test vectors (tests/aipl/encode/): random bytes encoded as
base64 (both alphabets, padded or not), hex, and percent-encoding (with
random sets of characters to keep, and `+` for spaces), as Python's base64,
binascii, and urllib.parse give them; and random texts heavy in edge cases
decoded, accepted or refused as Python accepts or refuses them
(binascii.a2b_base64 with strict_mode, binascii.unhexlify, and for
percent-encoding unquote_to_bytes where every `%` has two hex digits).

    python3 tools/encode_vectors.py tests/aipl/encode [seed]

Bytes go to the program as hex (a string literal cannot hold any byte), so
hex_decode is what reads every input; it is checked here too. Each case
prints one line: the result as hex, or "err". tests/test_encode.rs runs the
program in every backend against the answers.
"""
import base64, binascii, random, re, sys
from urllib.parse import quote, quote_plus, unquote_to_bytes

random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 1)
out = sys.argv[1]

def lit(s):  # an AIPL string literal for s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t") + '"'

def rand_bytes(n):
    # mostly random bytes, sometimes ASCII text, so both kinds of output show
    if random.random() < 0.4:
        return bytes(random.choice(b"ab Z09 /+-_.~%=?&\n\xc3\xa9") for _ in range(n))
    return bytes(random.randrange(256) for _ in range(n))

def b64_strict(s, url):
    if url:
        if "+" in s or "/" in s:
            return None
        s = s.replace("-", "+").replace("_", "/")
    try:
        return binascii.a2b_base64(s.encode(), strict_mode=True)
    except binascii.Error:
        return None

lines, want = [], []
def case(call, result):
    lines.append("    " + call)
    want.append("err" if result is None else result.hex())

# encoding
for _ in range(300):
    b = rand_bytes(random.randint(0, 20))
    url, pad = random.random() < 0.5, random.random() < 0.5
    e = (base64.urlsafe_b64encode if url else base64.b64encode)(b)
    if not pad:
        e = e.rstrip(b"=")
    alph = "encode.Alphabet.url_safe" if url else "encode.Alphabet.standard"
    padding = "encode.Padding.padded" if pad else "encode.Padding.unpadded"
    case(f'(call b64e "{b.hex()}" {alph} {padding})', e)
for _ in range(100):
    b = rand_bytes(random.randint(0, 12))
    upper = random.random() < 0.5
    h = b.hex().upper() if upper else b.hex()
    case(f'(call hexe "{b.hex()}" {"true" if upper else "false"})', h.encode())
for _ in range(300):
    b = rand_bytes(random.randint(0, 14))
    keep = "".join(random.sample("/:?&=+ !*'()$,;@#[]%", random.randint(0, 5)))
    plus = random.random() < 0.3
    q = quote_plus(b, safe=keep) if plus else quote(b, safe=keep)
    case(f'(call pcte "{b.hex()}" {lit(keep)} {"true" if plus else "false"})', q.encode())

# decoding: valid encodings, then near misses
alpha64 = list("QUJDRUZHabcz0189+/-_") + ["=", "==", "=", " ", "\n", "!", "A"]
for _ in range(500):
    url, pad = random.random() < 0.5, random.random() < 0.5
    if random.random() < 0.4:
        e = (base64.urlsafe_b64encode if url else base64.b64encode)(rand_bytes(random.randint(0, 10))).decode()
        if not pad:
            e = e.rstrip("=")
        if random.random() < 0.5 and e:  # one change
            i = random.randrange(len(e))
            e = e[:i] + random.choice(alpha64) + e[i + 1:]
    else:
        e = "".join(random.choice(alpha64) for _ in range(random.randint(0, 9)))
    if pad:
        r = b64_strict(e, url)
    else:
        n = len(e)
        ok = "=" not in e and n % 4 != 1
        r = b64_strict(e + "=" * ((4 - n % 4) % 4), url) if ok else None
    alph = "encode.Alphabet.url_safe" if url else "encode.Alphabet.standard"
    padding = "encode.Padding.padded" if pad else "encode.Padding.unpadded"
    case(f"(call b64d {lit(e)} {alph} {padding})", r)
for _ in range(150):
    h = "".join(random.choice("0123456789abcdefABCDEFg ") for _ in range(random.randint(0, 9)))
    try:
        r = binascii.unhexlify(h)
    except binascii.Error:
        r = None
    case(f"(call hexd {lit(h)})", r)
for _ in range(300):
    t = "".join(random.choice(["a", "%", "%4", "%41", "%c3%A9", "%zz", "+", " ", "/", "%2", "%%", "Z"]) for _ in range(random.randint(0, 7)))
    plus = random.random() < 0.4
    valid = re.fullmatch(r"([^%]|%[0-9a-fA-F]{2})*", t) is not None
    r = unquote_to_bytes(t.replace("+", " ") if plus else t) if valid else None
    case(f'(call pctd {lit(t)} {"true" if plus else "false"})', r)

src = ''';; Generated by tools/encode_vectors.py; do not edit.
(module vectors
  (import encode)
  (import str)
  (import buf)
  (import alloc)

  ;; the bytes whose hex digits are h (the inputs come this way)
  (fn bytes_of [h:str] -> str.Bytes
    (let o:(ptr buf.Buf) (call buf.make (call alloc.default) 16))
    (match_result (call encode.hex_decode_to o (call str.from_str h))
      (ok _n (call buf.bytes o))
      (err _at (call buf.bytes o))))

  ;; o's bytes as hex, on a line
  (fn show [o:(ptr buf.Buf)] -> void
    (let p:(ptr buf.Buf) (call buf.make (call alloc.default) 16))
    (call encode.hex_to p (call buf.bytes o) false)
    (call buf.push_byte p 10)
    (call buf.print p)
    (call buf.free p)
    (call buf.free o))

  (fn decoded [o:(ptr buf.Buf) r:(result i32 i32)] -> void
    (match_result r
      (ok _n (call show o))
      (err _at (call buf.free o) (sys.print "err"))))

  (fn fresh [] -> (ptr buf.Buf) (call buf.make (call alloc.default) 16))

  (fn b64e [h:str alphabet:encode.Alphabet padding:encode.Padding] -> void
    (let o:(ptr buf.Buf) (call fresh))
    (call encode.base64_to o (call bytes_of h) alphabet padding)
    (call show o))

  (fn hexe [h:str upper:bool] -> void
    (let o:(ptr buf.Buf) (call fresh))
    (call encode.hex_to o (call bytes_of h) upper)
    (call show o))

  (fn pcte [h:str keep:str plus:bool] -> void
    (let o:(ptr buf.Buf) (call fresh))
    (call encode.percent_encode_to o (call bytes_of h) keep plus)
    (call show o))

  (fn b64d [t:str alphabet:encode.Alphabet padding:encode.Padding] -> void
    (let o:(ptr buf.Buf) (call fresh))
    (call decoded o (call encode.base64_decode_to o (call str.from_str t) alphabet padding)))

  (fn hexd [t:str] -> void
    (let o:(ptr buf.Buf) (call fresh))
    (call decoded o (call encode.hex_decode_to o (call str.from_str t))))

  (fn pctd [t:str plus:bool] -> void
    (let o:(ptr buf.Buf) (call fresh))
    (call decoded o (call encode.percent_decode_to o (call str.from_str t) plus)))

  (fn main [] -> i32
''' + "\n".join(lines) + "\n    0))\n"
open(f"{out}/vectors.aipl", "w").write(src)
open(f"{out}/vectors.expected", "w").write("\n".join(want) + "\n")
print(f"{len(lines)} cases")
