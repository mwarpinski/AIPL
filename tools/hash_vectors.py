"""std/hash's test vectors (tests/aipl/hash/): MD5, SHA-1, SHA-256, and
SHA-512 of random bytes of every length up to a few blocks, whole and given
in three random pieces; HMAC over each with random keys of up to twice a
block (so long keys are hashed first), and RFC 4231's cases; CRC-32 and
Adler-32, whole and in two pieces; and constant_time_eq. The answers are
Python's hashlib, hmac, and zlib.

    python3 tools/hash_vectors.py tests/aipl/hash [seed]

Bytes go to the program as hex. Each case prints one line.
tests/test_hash.rs runs the program in every backend against the answers.
"""
import hashlib, hmac, random, sys, zlib

random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 1)
out = sys.argv[1]
algs = {"md5": 64, "sha1": 64, "sha256": 64, "sha512": 128}

def rand_bytes(n):
    return bytes(random.randrange(256) for _ in range(n))

def s32(v):
    return v - (1 << 32) if v >= 1 << 31 else v

lines, want = [], []
def case(call, result):
    lines.append("    " + call)
    want.append(result)

# NIST's examples (FIPS 180-2 appendices): "abc", "", and the 448- and
# 896-bit messages
nist = [b"abc", b"", b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq",
        b"abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmnhijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu"]
for m in nist:
    for a in algs:
        case(f'(call dig "{m.hex()}" hash.Algorithm.{a})', hashlib.new(a, m).hexdigest())
# every length up to 2 blocks and a bit, for each
for a, bs in algs.items():
    for n in range(0, 2 * bs + 20, 3 if bs == 128 else 2):
        m = rand_bytes(n)
        case(f'(call dig "{m.hex()}" hash.Algorithm.{a})', hashlib.new(a, m).hexdigest())
# in three pieces
for _ in range(120):
    a = random.choice(list(algs))
    m = rand_bytes(random.randint(0, 300))
    c1 = random.randint(0, len(m))
    c2 = random.randint(c1, len(m))
    case(f'(call pieces "{m.hex()}" hash.Algorithm.{a} {c1} {c2})', hashlib.new(a, m).hexdigest())
# HMAC: RFC 4231's keys and messages (cases 1-4, 6, 7), then random ones
rfc = [(b"\x0b" * 20, b"Hi There"), (b"Jefe", b"what do ya want for nothing?"),
       (b"\xaa" * 20, b"\xdd" * 50), (bytes(range(1, 26)), b"\xcd" * 50),
       (b"\xaa" * 131, b"Test Using Larger Than Block-Size Key - Hash Key First"),
       (b"\xaa" * 131, b"This is a test using a larger than block-size key and a larger than block-size data. The key needs to be hashed before being used by the HMAC algorithm.")]
for k, m in rfc:
    for a in ("sha256", "sha512"):
        case(f'(call mac "{k.hex()}" "{m.hex()}" hash.Algorithm.{a})', hmac.new(k, m, a).hexdigest())
for _ in range(120):
    a = random.choice(list(algs))
    k = rand_bytes(random.choice([0, 1, algs[a] - 1, algs[a], algs[a] + 1, random.randint(0, 2 * algs[a])]))
    m = rand_bytes(random.randint(0, 200))
    case(f'(call mac "{k.hex()}" "{m.hex()}" hash.Algorithm.{a})', hmac.new(k, m, a).hexdigest())
# checksums, whole and in two pieces
for _ in range(150):
    m = rand_bytes(random.choice([0, 1, 2, random.randint(0, 64), random.randint(0, 6000)]))
    cut = random.randint(0, len(m))
    case(f'(call sums "{m.hex()}" {cut})', f"{s32(zlib.crc32(m))} {s32(zlib.adler32(m))}")
# constant_time_eq
for _ in range(40):
    x = rand_bytes(random.randint(0, 8))
    y = bytearray(x)
    r = random.random()
    if r < 0.3 and y:
        y[random.randrange(len(y))] ^= 1 << random.randrange(8)
    elif r < 0.45:
        y = y + b"\x00"
    case(f'(call same "{x.hex()}" "{bytes(y).hex()}")', "true" if x == bytes(y) else "false")

src = ''';; Generated by tools/hash_vectors.py; do not edit.
(module vectors
  (import hash)
  (import encode)
  (import str)
  (import buf)
  (import alloc)

  ;; the bytes whose hex digits are h (the inputs come this way)
  (fn bytes_of [h:str] -> (ptr str.Bytes)
    (let o:(ptr buf.Buf) (call buf.make (call alloc.default) 16))
    (match_result (call encode.hex_decode_to o (call str.from_str h))
      (ok _n (call buf.bytes o))
      (err _at (call buf.bytes o))))

  ;; d's bytes as hex, on a line; frees d
  (fn show [d:(ptr buf.Buf)] -> void
    (let p:(ptr buf.Buf) (call buf.make (call alloc.default) 16))
    (call encode.hex_to p (call buf.bytes d) false)
    (call buf.push_byte p 10)
    (call buf.print p)
    (call buf.free p)
    (call buf.free d))

  (fn fresh [] -> (ptr buf.Buf) (call buf.make (call alloc.default) 64))

  (fn dig [h:str alg:hash.Algorithm] -> void
    (let d:(ptr buf.Buf) (call fresh))
    (call hash.digest_to d alg (call bytes_of h))
    (call show d))

  (fn pieces [h:str alg:hash.Algorithm c1:i32 c2:i32] -> void
    (let m:(ptr str.Bytes) (call bytes_of h))
    (let x:(ptr hash.Hasher) (call hash.make (call alloc.default) alg))
    (call hash.update x (call str.slice m 0 c1))
    (call hash.update x (call str.slice m c1 (- c2 c1)))
    (call hash.update x (call str.slice m c2 (- (get m str.Bytes.len) c2)))
    (let d:(ptr buf.Buf) (call fresh))
    (call hash.finish_to x d)
    (call hash.free x)
    (call show d))

  (fn mac [k:str m:str alg:hash.Algorithm] -> void
    (let d:(ptr buf.Buf) (call fresh))
    (call hash.hmac_to d alg (call bytes_of k) (call bytes_of m))
    (call show d))

  (fn sums [h:str cut:i32] -> void
    (let m:(ptr str.Bytes) (call bytes_of h))
    (let rest:(ptr str.Bytes) (call str.slice m cut (- (get m str.Bytes.len) cut)))
    (let c:i32 (call hash.crc32_update (call hash.crc32 (call str.slice m 0 cut)) rest))
    (let a:i32 (call hash.adler32_update (call hash.adler32 (call str.slice m 0 cut)) rest))
    (println "{c} {a}"))

  (fn same [x:str y:str] -> void
    (sys.print (if (call hash.constant_time_eq (call bytes_of x) (call bytes_of y)) "true" "false")))

  (fn main [] -> i32
''' + "\n".join(lines) + "\n    0))\n"
open(f"{out}/vectors.aipl", "w").write(src)
open(f"{out}/vectors.expected", "w").write("\n".join(want) + "\n")
print(f"{len(lines)} cases")
