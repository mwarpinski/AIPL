"""std/html's test vectors (tests/aipl/html/): random texts heavy in
character references (named ones std/html knows, with and without their
';', legacy prefixes of longer names, decimal and hex numbers including
huge ones, surrogates, the Windows-1252 range, controls, and names no
table has) unescaped, and random texts escaped with and without quotes,
as Python's html module does it. A text in which Python would find one of
HTML5's other names (std/html knows HTML 4's) is drawn again.

    python3 tools/html_vectors.py tests/aipl/html [seed]

Each case prints its result as hex. tests/test_html.rs runs the program
in every backend against the answers.
"""
import html, html.entities as E, random, re, sys

random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 1)
out = sys.argv[1]

legacy = [k for k in E.html5 if not k.endswith(";")]
known = set(E.name2codepoint) | {"apos"} | set(legacy)

def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r") + '"'

pieces = ["a", "b", " ", "é", ";", "&", "#", "x", "\n", "<", ">", '"', "'"]
def reference():
    r = random.random()
    if r < 0.35:
        name = random.choice(sorted(known))
        return "&" + name + random.choice([";", ";", ""])
    if r < 0.45:
        return "&" + random.choice(legacy) + random.choice(["it;", "x", "1;", "ab"])
    if r < 0.75:
        n = random.choice([0, 9, 13, 38, 65, 128, 129, 150, 159, 160, 0xD800, 0xDFFF, 0xFFFE, 0x1FFFF, 0x10FFFF, 0x110000, 10**12, random.randrange(0x3000), random.randrange(0x10FFFF)])
        form = random.choice(["&#%d", "&#x%x", "&#X%X"]) % n
        return form + random.choice([";", ""])
    return "&" + "".join(random.choice("abcqz") for _ in range(random.randint(0, 4))) + random.choice([";", ""])

rx = re.compile(r"&(#[0-9]+;?|#[xX][0-9a-fA-F]+;?|[^\t\n\f <&#;]{1,32};?)")
def safe(t):
    # every name Python would read here is one std/html knows
    for m in rx.finditer(t):
        s = m.group(1)
        if not s.startswith("#") and s in E.html5 and s.rstrip(";") not in known:
            return False
    return True

lines, want = [], []
def case(call, result):
    lines.append("    " + call)
    want.append(result.encode().hex())

n = 0
while n < 600:
    t = "".join(reference() if random.random() < 0.5 else random.choice(pieces) for _ in range(random.randint(0, 6)))
    if not safe(t):
        continue
    n += 1
    case(f"(call unesc {lit(t)})", html.unescape(t))
for _ in range(100):
    t = "".join(random.choice(pieces) for _ in range(random.randint(0, 10)))
    quote = random.random() < 0.5
    case(f"(call esc {lit(t)} {'true' if quote else 'false'})", html.escape(t, quote))

src = ''';; Generated by tools/html_vectors.py; do not edit.
(module vectors
  (import html)
  (import encode)
  (import str)
  (import buf)
  (import alloc)

  (fn show [o:(ptr buf.Buf)] -> void
    (let h:(ptr buf.Buf) (call buf.make (call alloc.default) 64))
    (call encode.hex_to h (call buf.bytes o) false)
    (call buf.push_byte h 10)
    (call buf.print h)
    (call buf.free h)
    (call buf.free o))

  (fn unesc [t:str] -> void
    (let o:(ptr buf.Buf) (call buf.make (call alloc.default) 64))
    (call html.unescape_to o (call str.from_str t))
    (call show o))

  (fn esc [t:str quote:bool] -> void
    (let o:(ptr buf.Buf) (call buf.make (call alloc.default) 64))
    (call html.escape_to o (call str.from_str t) quote)
    (call show o))

  (fn main [] -> i32
''' + "\n".join(lines) + "\n    0))\n"
open(f"{out}/vectors.aipl", "w").write(src)
open(f"{out}/vectors.expected", "w").write("\n".join(want) + "\n")
print(f"{len(lines)} cases")
