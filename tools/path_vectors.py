"""std/path's test vectors (tests/aipl/libs/path_demo.*): random paths
built from names, dots, double dots, and runs of slashes, each with what
Python's posixpath gives for join, dirname, basename, splitext, and
normpath.

    python3 tools/path_vectors.py tests/aipl/libs [seed]
"""
import posixpath as pp, random, sys
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 1)
out = sys.argv[1]
parts = ["a", "b", ".", "..", "x.tar.gz", ".hidden", "c.", "..d", "e.txt", ""]
def rnd():
    s = random.choice(["", "/", "//", "///"]) + "/".join(random.choice(parts) for _ in range(random.randint(0, 4)))
    return s + random.choice(["", "", "/", "//"])
lines, want = [], []
for _ in range(400):
    p, q = rnd(), rnd()
    root, ext = pp.splitext(p)
    lines.append(f'    (call case "{p}" "{q}")')
    want.append(" | ".join([pp.join(p, q), pp.dirname(p), pp.basename(p), pp.basename(root), ext, pp.normpath(p), str(pp.isabs(p)).lower()]))
src = ''';; Generated by tools/path_vectors.py; do not edit.
(module path_demo
  (import path)
  (fn case [p:str q:str] -> void
    (let j:str (call path.join p q))
    (let d:str (call path.parent p))
    (let f:str (call path.file_name p))
    (let s:str (call path.stem p))
    (let e:str (call path.extension p))
    (let n:str (call path.normalize p))
    (println "{j} | {d} | {f} | {s} | {e} | {n} | {(call path.is_absolute p)}"))
  (fn main [] -> i32
''' + "\n".join(lines) + '''
    0))
'''
open(f"{out}/path_demo.aipl", "w").write(src)
open(f"{out}/path_demo.expected", "w").write("".join(w + "\n" for w in want))
print(f"{len(want)} cases")
