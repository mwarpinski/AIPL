"""std/stats's test vectors (tests/aipl/stats/): random data sets (small
integers with repeats, uniform values, large values with a large offset,
tiny values, mixed magnitudes, constant data), each with what Python's
statistics module and math.fsum give, written with repr (which std/show
matches), so equal text is equal bits.

    python3 tools/stats_vectors.py tests/aipl/stats [seed]

tests/test_stats.rs runs the program in every backend against the answers.
"""
import math, random, statistics as st, sys
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 1)
out = sys.argv[1]

def lit(x):  # repr, with the decimal point AIPL's literals need
    s = repr(float(x))
    if "e" in s and "." not in s.split("e")[0]:
        a, b = s.split("e")
        s = a + ".0e" + b
    return s

def data(kind, n):
    if kind == 0: return [float(random.randint(-5, 5)) for _ in range(n)]
    if kind == 1: return [random.uniform(-100, 100) for _ in range(n)]
    if kind == 2: return [1e15 + random.uniform(-1, 1) * 1e6 for _ in range(n)]
    if kind == 3: return [random.uniform(0, 1) * 1e-12 for _ in range(n)]
    if kind == 4: return [random.choice([1e10, -1e10, 1.0, 3.5, -2.25, 1e-5, 7e7]) for _ in range(n)]
    return [2.5] * n

lines, want = [], []
for _ in range(300):
    kind, n = random.randint(0, 5), random.randint(1, 25)
    xs = data(kind, n)
    vals = [math.fsum(xs), st.fmean(xs), st.mean(xs), st.median(xs), min(xs), max(xs), st.mode(xs), st.pvariance(xs), st.pstdev(xs)]
    vals += st.quantiles(xs, n=4) + st.quantiles(xs, n=4, method="inclusive") + st.quantiles(xs, n=10)
    if n > 1:
        vals += [st.variance(xs), st.stdev(xs)]
        ys = data(random.randint(0, 4), n)
        vals.append(st.covariance(xs, ys))
        constant = len(set(xs)) == 1 or len(set(ys)) == 1
        if not constant:
            lr = st.linear_regression(xs, ys)
            vals += [st.correlation(xs, ys), lr.slope, lr.intercept]
        lines.append(f'    (call case2 "{" ".join(lit(x) for x in xs)}" "{" ".join(lit(y) for y in ys)}" {"true" if constant else "false"})')
    else:
        lines.append(f'    (call case1 "{lit(xs[0])}")')
    want.append(" ".join(repr(float(v)) for v in vals))

src = ''';; Generated by tools/stats_vectors.py; do not edit.
(module vectors
  (import stats)
  (import text)
  (import str)
  (import vec)
  (import alloc)
  (import buf)

  ;; the numbers in s
  (fn nums [s:str] -> (arr f64)
    (let a:alloc.Allocator (call alloc.default))
    (let fs:(ptr (vec.Vec (ptr str.Bytes))) (call text.fields a (call str.from_str s)))
    (let xs:(arr f64) (arr.new f64 (call (vec.len (ptr str.Bytes)) fs)))
    (for k 0 (arr.len xs)
      (match_result (call text.parse_f64 (call (vec.at (ptr str.Bytes)) fs k))
        (ok x (arr.set f64 xs k x))
        (err _e (block))))
    xs)

  (fn put [b:(ptr buf.Buf) x:f64] -> void
    (when (gt (call buf.len b) 0) (call buf.push_byte b 32))
    (format_to b "{x}"))

  (fn one [b:(ptr buf.Buf) xs:(arr f64)] -> void
    (let a:alloc.Allocator (call alloc.default))
    (call put b (call stats.sum xs))
    (call put b (call stats.fmean xs))
    (call put b (call stats.mean xs))
    (call put b (call stats.median xs))
    (call put b (call stats.min xs))
    (call put b (call stats.max xs))
    (call put b (call stats.mode xs))
    (call put b (call stats.pvariance xs))
    (call put b (call stats.pstdev xs))
    (let q4:(arr f64) (call stats.quantiles a xs 4 false))
    (for k 0 (arr.len q4) (call put b (arr.get f64 q4 k)))
    (let i4:(arr f64) (call stats.quantiles a xs 4 true))
    (for k 0 (arr.len i4) (call put b (arr.get f64 i4 k)))
    (let q10:(arr f64) (call stats.quantiles a xs 10 false))
    (for k 0 (arr.len q10) (call put b (arr.get f64 q10 k))))

  (fn case1 [s:str] -> void
    (let b:(ptr buf.Buf) (call buf.make (call alloc.default) 256))
    (call one b (call nums s))
    (call buf.push_byte b 10)
    (call buf.print b)
    (call buf.free b))

  (fn case2 [s:str t:str constant:bool] -> void
    (let b:(ptr buf.Buf) (call buf.make (call alloc.default) 256))
    (let xs:(arr f64) (call nums s))
    (let ys:(arr f64) (call nums t))
    (call one b xs)
    (call put b (call stats.variance xs))
    (call put b (call stats.stdev xs))
    (call put b (call stats.covariance xs ys))
    (when (not constant)
      (let f:stats.Fit (call stats.linear_fit xs ys))
      (call put b (call stats.correlation xs ys))
      (call put b (get f stats.Fit.slope))
      (call put b (get f stats.Fit.intercept)))
    (call buf.push_byte b 10)
    (call buf.print b)
    (call buf.free b))

  (fn main [] -> i32
''' + "\n".join(lines) + '''
    0))
'''
open(f"{out}/vectors.aipl", "w").write(src)
open(f"{out}/vectors.expected", "w").write("".join(w + "\n" for w in want))
print(f"{len(want)} cases")
