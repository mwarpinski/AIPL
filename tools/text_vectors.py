"""std/text's and std/str's test vectors (tests/aipl/text/): random short
strings over a small alphabet (spaces, commas, tabs, newlines, carriage
returns, a two-byte character), split, split on whitespace, split into
lines, replaced, searched, counted, and trimmed, with what Python (and, for
lines, Rust's str::lines) gives for each.

    python3 tools/text_vectors.py tests/aipl/text [seed]

tests/test_text.rs runs the program in every backend against the answers.
"""
import random, sys
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 1)
out = sys.argv[1]
alpha = ["a", "b", "ab", " ", ",", "\\n", "\\t", "x", "aa", "é"]
def rnd(n):
    return "".join(random.choice(alpha) for _ in range(random.randint(0, n)))
def py(s):  # the AIPL literal's text -> the Python string
    return s.replace("\\n", "\n").replace("\\t", "\t").replace("\\r", "\r")
def lit(s): return '"' + s + '"'
def show(parts): return "|".join(p.replace("\n", "\\n").replace("\t", "\\t") for p in parts)
lines, want = [], []
def case(code, expect):
    lines.append(f"    {code}")
    want.append(expect)
for _ in range(100):
    s, sep = rnd(12), random.choice([",", "a", "ab", " ", "aa"])
    case(f'(call pr (call text.split a (call str.from_str {lit(s)}) (call str.from_str {lit(sep)})))', show(py(s).split(py(sep))))
    case(f'(call pr (call text.fields a (call str.from_str {lit(s)})))', show(py(s).split()))
    t = rnd(10)
    case(f'(call pb (call text.replace a (call str.from_str {lit(s)}) (call str.from_str {lit(sep)}) (call str.from_str {lit(t)})))', show([py(s).replace(py(sep), py(t))]))
    case(f'(call pi (call str.find (call str.from_str {lit(s)}) (call str.from_str {lit(sep)})))', str(py(s).encode().find(py(sep).encode())))
    case(f'(call pi (call str.rfind (call str.from_str {lit(s)}) (call str.from_str {lit(sep)})))', str(py(s).encode().rfind(py(sep).encode())))
    case(f'(call pi (call str.count (call str.from_str {lit(s)}) (call str.from_str {lit(sep)})))', str(py(s).encode().count(py(sep).encode())))
    case(f'(call pb1 (call str.trim (call str.from_str {lit(s)})))', show([py(s).strip(" \t\n\r\x0b\x0c")]))
    u = rnd(14).replace("\\t", "\\r")
    ps = py(u)
    exp = ps.split("\n")
    if exp and exp[-1] == "": exp = exp[:-1]
    # a \r is dropped only before a \n (Rust's str::lines)
    ended = ps.endswith("\n")
    exp = [e[:-1] if e.endswith("\r") and (k < len(exp) - 1 or ended) else e for k, e in enumerate(exp)]
    case(f'(call pr (call text.lines a (call str.from_str {lit(u)})))', show(exp).replace("\r", "\\r"))
src = ''';; Generated by tools/text_vectors.py; do not edit.
(module vectors
  (import str)
  (import text)
  (import vec)
  (import buf)
  (import alloc)
  (fn pr [v:(ptr (vec.Vec (ptr str.Bytes)))] -> void
    (let b:(ptr buf.Buf) (call text.join (call alloc.default) v (call str.from_str "|")))
    (call pb b))
  (fn pb [b:(ptr buf.Buf)] -> void (call pb1 (call buf.bytes b)))
  ;; newlines, tabs, and carriage returns escaped, so each case is one line
  (fn pb1 [s:(ptr str.Bytes)] -> void
    (let o:(ptr buf.Buf) (call buf.make (call alloc.default) 16))
    (loop i 0 (- (get s str.Bytes.len) 1) 1
      (let c:i32 (call str.byte_at s i))
      (cond ((eq c 10) (call buf.push_str o "\\\\n")) ((eq c 9) (call buf.push_str o "\\\\t")) ((eq c 13) (call buf.push_str o "\\\\r")) (else (call buf.push_byte o c))))
    (call buf.push_byte o 10)
    (call buf.print o))
  (fn pi [n:i32] -> void (println "{n}"))
  (fn main [] -> i32
    (let a:alloc.Allocator (call alloc.default))
''' + "\n".join(lines) + "\n    0))\n"
open(out + "/vectors.aipl", "w").write(src)
open(out + "/vectors.expected", "w").write("\n".join(want) + "\n")
print(len(want), "cases")
